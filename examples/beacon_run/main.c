static float fog_amount(void) {  // 0 clear .. 1 thickest
    return 1.0f - clamp01((visibility - VIS_MIN) / (VIS_START - VIS_MIN));
}

static void camera_tick(float dt) {
    Vector3 desired, target;
    if (state == STATE_TITLE) {
        float a = title_time * 0.08f;
        desired = (Vector3){ sinf(a) * 150.0f, 75.0f, cosf(a) * 150.0f };
        target = (Vector3){ 0.0f, 10.0f, 0.0f };
        camera.position = desired;
    } else {
        Vector3 f, r, u;
        glider_axes(&glider, &f, &r, &u);
        Vector3 flat = { sinf(glider.yaw), 0.0f, -cosf(glider.yaw) };
        if (state == STATE_PLAYING || state == STATE_PAUSED) {
            desired = vector3_add(glider.position, vector3_add(vector3_scale(flat, -10.0f), (Vector3){ 0.0f, 3.5f, 0.0f }));
        } else {  // after the run: slowly orbit the glider
            float a = glider.yaw + crash_timer * 0.25f;
            desired = vector3_add(glider.position, (Vector3){ -sinf(a) * 16.0f, 7.0f, cosf(a) * 16.0f });
        }
        target = vector3_add(glider.position, vector3_scale(f, 4.0f));
        if (state != STATE_PAUSED) {
            float k = 1.0f - expf(-5.0f * dt);
            camera.position = vector3_add(camera.position, vector3_scale(vector3_subtract(desired, camera.position), k));
        }
        float floor_y = surface_height(camera.position.x, camera.position.z) + 1.5f;
        if (camera.position.y < floor_y) camera.position.y = floor_y;
    }
    camera.target = target;
    camera.up = VECTOR3_UP;
    camera3d_update(&camera);
    float far = state == STATE_TITLE ? 400.0f : visibility + 20.0f;
    camera3d_set_perspective(camera.projection, deg_to_rad(70.0f), (float)screen_size.x / (float)screen_size.y, 0.2f, far);
}

