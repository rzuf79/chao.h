static void draw_end_screen(void) {
    int w = screen_size.x, h = screen_size.y;
    if (crash_timer < 1.2f) return;  // let the message pop play first
    chao_blend_mode = BLEND_ALPHA;
    fill_rect(chao_canvas, w / 2 - 110, h / 2 - 50, 220, 100, 0x00000090);
    chao_blend_mode = BLEND_NONE;
    const char* title = state == STATE_WON ? "ISLAND SAVED!" : state == STATE_CRASHED ? "CRASHED" : "LOST IN THE FOG";
    uint32_t color = state == STATE_WON ? 0xFFC860FF : 0xFF7060FF;
    big_text(w / 2, h / 2 - 32, 2.0f, color, 1.0f, title);
    char t[16];
    format_time(t, sizeof t, elapsed);
    text(w / 2, h / 2 - 12, COLOR_WHITE, TEXT_ALIGN_CENTER, "beacons %d/%d   time %s", beacons_lit, BEACON_COUNT, t);
    if (best_time >= 0.0f) {
        char b[16];
        format_time(b, sizeof b, best_time);
        text(w / 2, h / 2, 0xFFC860FF, TEXT_ALIGN_CENTER, "best %s", b);
    }
    text(w / 2, h / 2 + 18, 0xE0E0E0FF, TEXT_ALIGN_CENTER, "R  retry this island");
    text(w / 2, h / 2 + 30, 0xE0E0E0FF, TEXT_ALIGN_CENTER, "N  new island   Esc  title");
}

static void game_draw(float dt) {
    camera_tick(dt);
    draw_world();
    switch (state) {
        case STATE_TITLE:
            draw_title();
            break;
        case STATE_PLAYING:
            draw_hud();
            break;
        case STATE_PAUSED:
            draw_hud();
            chao_blend_mode = BLEND_ALPHA;
            fill_rect(chao_canvas, screen_size.x / 2 - 100, screen_size.y / 2 - 28, 200, 50, 0x00000090);
            chao_blend_mode = BLEND_NONE;
            big_text(screen_size.x / 2, screen_size.y / 2 - 10, 2.0f, COLOR_WHITE, 1.0f, "PAUSED");
            text(screen_size.x / 2, screen_size.y / 2 + 10, 0xE0E0E0FF, TEXT_ALIGN_CENTER, "Esc resume   Q quit to title");
            break;
        case STATE_CRASHED:
        case STATE_LOST:
        case STATE_WON:
            draw_end_screen();
            break;
    }
    if (state == STATE_PLAYING || ((state == STATE_CRASHED || state == STATE_LOST || state == STATE_WON) && crash_timer < 1.2f)) {
        big_text(screen_size.x / 2, screen_size.y / 2 - 40, message_scale, 0xFFE0A0FF, message_alpha, message);
    }
}

