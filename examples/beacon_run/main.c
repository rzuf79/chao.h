static void spark_spawn(Vector3 p, Vector3 v, float life, float size, float rise, float drag, uint32_t c0, uint32_t c1) {
    for (int i = 0; i < MAX_SPARKS; ++i) {
        if (sparks[i].age < sparks[i].life) continue;
        sparks[i] = (Spark){ p, v, 0.0f, life, size, rise, drag, c0, c1 };
        return;
    }
}

static void sparks_tick(float dt) {
    for (int i = 0; i < MAX_SPARKS; ++i) {
        Spark* p = &sparks[i];
        if (p->age >= p->life) continue;
        p->age += dt;
        p->velocity.y += p->rise * dt;
        p->velocity = vector3_scale(p->velocity, fmaxf(0.0f, 1.0f - p->drag * dt));
        p->position = vector3_add(p->position, vector3_scale(p->velocity, dt));
    }
}

static void sparks_clear(void) {
    for (int i = 0; i < MAX_SPARKS; ++i) sparks[i].age = sparks[i].life = 0.0f;
}

static void sparks_draw(void) {
    chao_blend_mode = BLEND_ALPHA;
    for (int i = 0; i < MAX_SPARKS; ++i) {
        Spark* p = &sparks[i];
        if (p->age >= p->life) continue;
        float t = p->age / p->life;
        uint32_t c = lerp_color(p->color_start, p->color_end, t);
        uint32_t a = (uint32_t)((c & 0xFF) * (1.0f - t * t));
        draw_point3d(chao_canvas, &camera, p->position, p->size, (c & 0xFFFFFF00) | a);
    }
    chao_blend_mode = BLEND_NONE;
}

// Flames on lit beacons and motes rising in thermals, only near the player.
static void spawn_ambient_sparks(float dt) {
    spawn_accumulator += dt;
    while (spawn_accumulator >= 1.0f / 60.0f) {
        spawn_accumulator -= 1.0f / 60.0f;
        for (int b = 0; b < BEACON_COUNT; ++b) {
            const Beacon* bc = &island.beacons[b];
            if (!bc->lit || horizontal_distance(bc->fire, camera.position) > visibility) continue;
            Vector3 p = vector3_add(bc->fire, (Vector3){ randf(-0.6f, 0.6f), randf(0.0f, 0.8f), randf(-0.6f, 0.6f) });
            spark_spawn(p, (Vector3){ randf(-0.4f, 0.4f), randf(2.0f, 4.0f), randf(-0.4f, 0.4f) },
                           randf(0.7f, 1.3f), randf(0.5f, 0.9f), 1.5f, 0.5f, 0xFFD060FF, 0xC02010FF);
        }
        for (int i = 0; i < island.thermal_count; ++i) {
            const Thermal* t = &island.thermals[i];
            float dx = t->x - glider.position.x, dz = t->z - glider.position.z;
            if (dx * dx + dz * dz > 90.0f * 90.0f) continue;
            if ((rand() & 1) == 0) continue;  // ~30 per second per thermal
            float a = randf(0.0f, 6.2832f), d = sqrtf(randf(0.0f, 1.0f)) * t->radius;
            float y = clamp(glider.position.y + randf(-25.0f, 25.0f), WATER_LEVEL + 1.0f, CLOUD_BASE);
            Vector3 p = { t->x + cosf(a) * d, y, t->z + sinf(a) * d };
            spark_spawn(p, (Vector3){ 0.0f, randf(4.0f, 7.0f), 0.0f }, randf(1.8f, 2.8f), 0.35f, 0.0f, 0.0f,
                           0xFFFFFFB0, 0xFFFFFF00);
        }
    }
}

static void burst(Vector3 at, int count, float speed, uint32_t c0, uint32_t c1, float size, float rise) {
    for (int i = 0; i < count; ++i) {
        Vector3 d = vector3_get_normalized((Vector3){ randf(-1, 1), randf(-0.3f, 1.0f), randf(-1, 1) });
        spark_spawn(at, vector3_scale(d, randf(speed * 0.4f, speed)), randf(0.8f, 1.8f), size, rise, 1.2f, c0, c1);
    }
}

