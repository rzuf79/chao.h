// Unscaled hills (noise, faded out toward the coast) and the coast fade itself.
static float island_hills(float x, float z, float* mask) {
    float nx = x * 0.012f + island.noise_offset.x;
    float nz = z * 0.012f + island.noise_offset.y;
    float n = noise_fbm(nx, nz, 0.5f, 5, 2.0f, 0.5f);
    n = n > 0.0f ? n * (1.0f + n * 0.9f) : n * 0.6f;
    float d = sqrtf(x * x + z * z);
    *mask = 1.0f - smoothstepf(ISLAND_RADIUS * 0.55f, ISLAND_RADIUS, d);
    return (n + 0.35f) * *mask;
}

// Terrain height before the sea flattens it: scaled hills, sinking under the sea past the coast.
static float ground_height(float x, float z) {
    float mask;
    float hills = island_hills(x, z, &mask);
    return hills * island.height_scale + (mask - 1.0f) * 14.0f;
}

static float terrain_height_cb(float x, float z, void* user) {
    (void)user;
    return fmaxf(ground_height(x, z), WATER_LEVEL);
}

// Height of the rendered surface at (x, z): the same triangles the mesh uses, so collision
// matches the picture exactly. Outside the grid it's open sea.
static float surface_height(float x, float z) {
    float gx = (x + WORLD_HALF) / CELL_SIZE;
    float gz = (z + WORLD_HALF) / CELL_SIZE;
    if (gx < 0.0f || gz < 0.0f || gx >= GRID || gz >= GRID) return WATER_LEVEL;
    int i = (int)gx, j = (int)gz;
    float fx = gx - i, fz = gz - j;
    const int side = GRID + 1;
    float ha = island.heights[j * side + i];
    float hb = island.heights[j * side + i + 1];
    float hc = island.heights[(j + 1) * side + i];
    float hd = island.heights[(j + 1) * side + i + 1];
    // each cell is split along the b-c diagonal, like model3d_create_heightmap does
    if (fx + fz <= 1.0f) return ha + (hb - ha) * fx + (hc - ha) * fz;
    return hd + (hc - hd) * (1.0f - fx) + (hb - hd) * (1.0f - fz);
}

static Vector3 surface_normal(float x, float z) {
    float e = CELL_SIZE * 0.5f;
    float dx = surface_height(x + e, z) - surface_height(x - e, z);
    float dz = surface_height(x, z + e) - surface_height(x, z - e);
    return vector3_get_normalized((Vector3){ -dx, 2.0f * e, -dz });
}

static Vector3 mix3(Vector3 a, Vector3 b, float t) {
    t = clamp01(t);
    return (Vector3){ lerp(a.x, b.x, t), lerp(a.y, b.y, t), lerp(a.z, b.z, t) };
}

static uint32_t island_color(float x, float z) {
    float h = ground_height(x, z);
    float slope = 1.0f - surface_normal(x, z).y;  // 0 flat .. 1 vertical
    float detail = noise_perlin(x * 0.35f, z * 0.35f, 7.3f) * 0.5f + 0.5f;
    float patches = noise_perlin(x * 0.05f + 40.0f, z * 0.05f, 1.7f) * 0.5f + 0.5f;

    const Vector3 deep    = { DEEP_WATER_R, DEEP_WATER_G, DEEP_WATER_B };
    const Vector3 shallow = { 0.20f, 0.52f, 0.66f };
    const Vector3 sand    = { 0.84f, 0.78f, 0.56f };
    const Vector3 grass   = { 0.33f, 0.58f, 0.24f };
    const Vector3 forest  = { 0.15f, 0.36f, 0.17f };
    const Vector3 rock    = { 0.47f, 0.44f, 0.41f };
    const Vector3 snow    = { 0.95f, 0.96f, 0.98f };

    Vector3 c;
    if (h < WATER_LEVEL) {
        c = mix3(deep, shallow, 1.0f + (h - WATER_LEVEL) / 6.0f);
    } else {
        c = mix3(grass, forest, smoothstepf(0.45f, 0.65f, patches));
        c = mix3(sand, c, smoothstepf(WATER_LEVEL + 0.4f, WATER_LEVEL + 1.6f, h));
        c = mix3(c, rock, smoothstepf(0.22f, 0.38f, slope));
        float snow_line = island.max_height * 0.78f + (detail - 0.5f) * 3.0f;
        c = mix3(c, snow, smoothstepf(snow_line, snow_line + 1.5f, h) * (1.0f - smoothstepf(0.35f, 0.5f, slope)));
        c = vector3_scale(c, 0.9f + detail * 0.2f);
    }
    return rgbf(c.x, c.y, c.z);
}

static void place_beacons(void) {
    // Candidates: local maxima on a coarse grid, highest first.
    typedef struct { float x, z, h; } Spot;
    static Spot spots[4096];
    int count = 0;
    const float step = 4.0f;
    for (float z = -ISLAND_RADIUS; z <= ISLAND_RADIUS; z += step) {
        for (float x = -ISLAND_RADIUS; x <= ISLAND_RADIUS; x += step) {
            float h = surface_height(x, z);
            if (h < WATER_LEVEL + 6.0f) continue;
            bool peak = true;
            for (int k = 0; k < 8 && peak; ++k) {
                float a = k * (float)M_PI / 4.0f;
                if (surface_height(x + cosf(a) * step, z + sinf(a) * step) > h) peak = false;
            }
            if (peak && count < 4096) spots[count++] = (Spot){ x, z, h };
        }
    }
    // also allow any high ground, used only if there aren't enough peaks
    int peaks = count;
    for (float z = -ISLAND_RADIUS; z <= ISLAND_RADIUS && count < 4096; z += step * 2) {
        for (float x = -ISLAND_RADIUS; x <= ISLAND_RADIUS && count < 4096; x += step * 2) {
            float h = surface_height(x, z);
            if (h >= WATER_LEVEL + 3.0f) spots[count++] = (Spot){ x, z, h };
        }
    }
    // sort each group by height (insertion sort, a few hundred items)
    for (int group = 0; group < 2; ++group) {
        int lo = group == 0 ? 0 : peaks, hi = group == 0 ? peaks : count;
        for (int i = lo + 1; i < hi; ++i) {
            Spot s = spots[i];
            int j = i - 1;
            while (j >= lo && spots[j].h < s.h) { spots[j + 1] = spots[j]; --j; }
            spots[j + 1] = s;
        }
    }

    int placed = 0;
    const float spacings[] = { 55.0f, 42.0f, 30.0f, 20.0f, 12.0f };
    for (int pass = 0; pass < 5 && placed < BEACON_COUNT; ++pass) {
        for (int i = 0; i < count && placed < BEACON_COUNT; ++i) {
            bool ok = true;
            for (int b = 0; b < placed; ++b) {
                float dx = spots[i].x - island.beacons[b].base.x, dz = spots[i].z - island.beacons[b].base.z;
                if (dx * dx + dz * dz < spacings[pass] * spacings[pass]) { ok = false; break; }
            }
            if (!ok) continue;
            Beacon* bc = &island.beacons[placed++];
            bc->base = (Vector3){ spots[i].x, spots[i].h, spots[i].z };
            bc->fire = (Vector3){ spots[i].x, spots[i].h + PILLAR_HEIGHT + 0.8f, spots[i].z };
            bc->lit = false;
        }
    }
    // A flat island could in theory run out of spots; stack the rest on the last one found.
    for (int b = placed; b < BEACON_COUNT; ++b) {
        island.beacons[b] = island.beacons[placed > 0 ? placed - 1 : 0];
        if (placed == 0) {
            island.beacons[b].base = (Vector3){ 0, surface_height(0, 0), 0 };
            island.beacons[b].fire = vector3_add(island.beacons[b].base, (Vector3){ 0, PILLAR_HEIGHT + 0.8f, 0 });
        }
    }
}

// How much the terrain inside a thermal's circle rises above its centre. Circling to climb
// next to a slope that rises above you means flying into it, so lower is better.
static float thermal_spot_rise(float x, float z) {
    float h = surface_height(x, z);
    float rise = 0.0f;
    for (int ring = 1; ring <= 3; ++ring) {
        float rr = THERMAL_RADIUS * 0.9f * ring / 3.0f;  // a full-bank circle is ~14 wide
        for (int k = 0; k < 12; ++k) {
            float a = k * (float)M_PI / 6.0f;
            rise = fmaxf(rise, surface_height(x + cosf(a) * rr, z + sinf(a) * rr) - h);
        }
    }
    return rise;
}

static bool thermal_spacing_ok(float x, float z, float spacing) {
    for (int t = 0; t < island.thermal_count; ++t) {
        float dx = x - island.thermals[t].x, dz = z - island.thermals[t].z;
        if (dx * dx + dz * dz < spacing * spacing) return false;
    }
    return true;
}

static bool thermal_spot_ok(float x, float z, float spacing, float max_rise) {
    if (surface_height(x, z) < WATER_LEVEL + 1.0f) return false;  // thermals rise over land
    return thermal_spacing_ok(x, z, spacing) && thermal_spot_rise(x, z) <= max_rise;
}

static void add_thermal(float x, float z) {
    Thermal* t = &island.thermals[island.thermal_count++];
    t->x = x;
    t->z = z;
    t->radius = rng_float(THERMAL_RADIUS * 0.85f, THERMAL_RADIUS * 1.15f);
    t->strength = rng_float(THERMAL_LIFT * 0.85f, THERMAL_LIFT * 1.1f);
    t->cloud_yaw = rng_float(0.0f, 6.28f);
}

static void place_thermals(void) {
    island.thermal_count = 0;
    // One near every beacon, so each can be reached: the clearest spot out of many tries,
    // preferring land.
    for (int b = 0; b < BEACON_COUNT; ++b) {
        Vector3 p = island.beacons[b].base;
        float best_score = 1e9f, best_x = p.x + 30.0f, best_z = p.z;
        for (int attempt = 0; attempt < 200; ++attempt) {
            float a = rng_float(0.0f, 6.2832f), d = rng_float(26.0f, 60.0f);
            float x = p.x + cosf(a) * d, z = p.z + sinf(a) * d;
            if (!thermal_spacing_ok(x, z, 30.0f)) continue;
            float score = thermal_spot_rise(x, z) + (surface_height(x, z) < WATER_LEVEL + 1.0f ? 20.0f : 0.0f);
            if (score < best_score) { best_score = score; best_x = x; best_z = z; }
            if (score <= 3.0f) break;  // good enough
        }
        add_thermal(best_x, best_z);
    }
    // one near the start, then the rest anywhere over land, relaxing the rules if needed
    for (int attempt = 0; attempt < 60 && island.thermal_count < BEACON_COUNT + 1; ++attempt) {
        float x = rng_float(-30.0f, 30.0f), z = rng_float(40.0f, 80.0f);
        if (thermal_spot_ok(x, z, 30.0f, 6.0f)) add_thermal(x, z);
    }
    const float spacings[] = { 38.0f, 32.0f, 26.0f };
    const float rises[] = { 6.0f, 8.0f, 10.0f };
    for (int pass = 0; pass < 3; ++pass) {
        for (int attempt = 0; attempt < 400 && island.thermal_count < THERMAL_COUNT; ++attempt) {
            float a = rng_float(0.0f, 6.2832f), d = sqrtf(rng_float(0.0f, 1.0f)) * ISLAND_RADIUS;
            float x = cosf(a) * d, z = sinf(a) * d;
            if (thermal_spot_ok(x, z, spacings[pass], rises[pass])) add_thermal(x, z);
        }
    }
}

static void island_generate(uint32_t seed) {
    island.seed = seed;
    rng_state = seed * 2654435761u + 0x9E3779B9u;
    if (rng_state == 0) rng_state = 1;
    island.noise_offset = (Vector2){ rng_float(0.0f, 200.0f) + 0.37f, rng_float(0.0f, 200.0f) + 0.71f };

    // Noise gives very flat or very tall islands; scale every island to a similar peak height.
    // The coast term (mask - 1) * 14 is never positive, so the highest point is at most
    // height_scale * (highest unscaled hill).
    float raw_peak = 0.0f;
    for (float z = -ISLAND_RADIUS; z <= ISLAND_RADIUS; z += CELL_SIZE) {
        for (float x = -ISLAND_RADIUS; x <= ISLAND_RADIUS; x += CELL_SIZE) {
            float mask;
            raw_peak = fmaxf(raw_peak, island_hills(x, z, &mask));
        }
    }
    island.height_scale = rng_float(PEAK_MIN, PEAK_MAX) / fmaxf(raw_peak, 0.05f);

    if (island.terrain) {
        free_bitmap(island.terrain->texture);
        model3d_free(island.terrain);
    }
    island.terrain = model3d_create_heightmap(GRID, CELL_SIZE, terrain_height_cb, NULL);
    island.max_height = WATER_LEVEL;
    for (int i = 0; i < (GRID + 1) * (GRID + 1); ++i) {
        island.heights[i] = island.terrain->vertices[i].y;
        island.max_height = fmaxf(island.max_height, island.heights[i]);
    }

    Bitmap* tex = create_bitmap(TEXTURE_SIZE, TEXTURE_SIZE);
    for (int y = 0; y < TEXTURE_SIZE; ++y) {
        for (int x = 0; x < TEXTURE_SIZE; ++x) {
            // texel centres, matching how the rasterizer maps UVs (u * size)
            float wx = ((x + 0.5f) / TEXTURE_SIZE) * WORLD_SIZE - WORLD_HALF;
            float wz = ((y + 0.5f) / TEXTURE_SIZE) * WORLD_SIZE - WORLD_HALF;
            tex->pixels[y * TEXTURE_SIZE + x] = island_color(wx, wz);
        }
    }
    island.terrain->texture = tex;

    place_beacons();
    place_thermals();
}

