static uint32_t rng_state = 1;
static uint32_t rng_next(void) {  // xorshift32: world generation must not depend on rand()
    rng_state ^= rng_state << 13;
    rng_state ^= rng_state >> 17;
    rng_state ^= rng_state << 5;
    return rng_state;
}
static float rng_float(float lo, float hi) {
    return lo + (hi - lo) * (float)(rng_next() & 0xFFFFFF) / (float)0x1000000;
}
static float randf(float lo, float hi) {  // cosmetic randomness (particles)
    return lo + (hi - lo) * (float)rand() / (float)RAND_MAX;
}

static uint32_t rgbf(float r, float g, float b) {
    return ((uint32_t)(clamp01(r) * 255.0f + 0.5f) << 24) |
           ((uint32_t)(clamp01(g) * 255.0f + 0.5f) << 16) |
           ((uint32_t)(clamp01(b) * 255.0f + 0.5f) << 8) | 0xFF;
}

static float smoothstepf(float e0, float e1, float x) {
    float t = clamp01((x - e0) / (e1 - e0));
    return t * t * (3.0f - 2.0f * t);
}

static float wrap_angle(float a) {
    while (a > (float)M_PI) a -= 2.0f * (float)M_PI;
    while (a < -(float)M_PI) a += 2.0f * (float)M_PI;
    return a;
}

static float approach(float value, float target, float step) {
    if (value < target) return fminf(value + step, target);
    return fmaxf(value - step, target);
}

static float horizontal_distance(Vector3 a, Vector3 b) {
    float dx = a.x - b.x, dz = a.z - b.z;
    return sqrtf(dx * dx + dz * dz);
}

static void format_time(char* out, size_t size, float seconds) {
    int s = (int)seconds;
    snprintf(out, size, "%d:%02d", s / 60, s % 60);
}

