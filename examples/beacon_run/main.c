// Model matrix from a basis (right, up, forward) and a position. Model space faces -Z.
static void basis_matrix(Matrix4 m, Vector3 r, Vector3 u, Vector3 f, Vector3 p) {
    MATRIX4_SET(m,
        r.x, u.x, -f.x, p.x,
        r.y, u.y, -f.y, p.y,
        r.z, u.z, -f.z, p.z,
        0,   0,   0,    1);
}

static void draw_model_at(Model3D* model, Vector3 position, float yaw, float scale) {
    Vector3 f = { sinf(yaw), 0.0f, -cosf(yaw) };
    Vector3 r = { cosf(yaw), 0.0f, sinf(yaw) };
    Matrix4 m;
    basis_matrix(m, vector3_scale(r, scale), (Vector3){ 0, scale, 0 }, vector3_scale(f, scale), position);
    draw_model3d_m(chao_canvas, &camera, model, m);
}

