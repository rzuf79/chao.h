static void glider_axes(const Glider* g, Vector3* forward, Vector3* right, Vector3* up) {
    float cp = cosf(g->pitch), sp = sinf(g->pitch);
    float cy = cosf(g->yaw), sy = sinf(g->yaw);
    Vector3 f = { cp * sy, sp, -cp * cy };
    Vector3 r0 = { cy, 0.0f, sy };
    Vector3 u0 = vector3_cross(r0, f);
    float cb = cosf(g->bank), sb = sinf(g->bank);
    *forward = f;
    *right = vector3_subtract(vector3_scale(r0, cb), vector3_scale(u0, sb));
    *up = vector3_add(vector3_scale(u0, cb), vector3_scale(r0, sb));
}

static Vector3 glider_point(const Glider* g, Vector3 local) {
    Vector3 f, r, u;
    glider_axes(g, &f, &r, &u);
    return vector3_add(g->position, vector3_add(vector3_add(vector3_scale(r, local.x), vector3_scale(u, local.y)), vector3_scale(f, -local.z)));
}

static float thermal_lift_at(Vector3 p, bool* inside) {
    float lift = 0.0f;
    *inside = false;
    for (int i = 0; i < island.thermal_count; ++i) {
        const Thermal* t = &island.thermals[i];
        float dx = p.x - t->x, dz = p.z - t->z;
        float d2 = (dx * dx + dz * dz) / (t->radius * t->radius);
        if (d2 >= 1.0f) continue;
        float top_fade = clamp01((CLOUD_BASE - p.y) / 15.0f);  // weakens just under the cloud
        lift += t->strength * (1.0f - d2) * top_fade;
        *inside = true;
    }
    return lift;
}

// Is the glider touching the ground, the sea or a beacon pillar?
static bool glider_collides(const Glider* g) {
    Vector3 points[] = {
        g->position,
        glider_point(g, (Vector3){ 0.0f, 0.10f, -1.8f }),  // nose
        glider_point(g, (Vector3){ -1.5f, 0.25f, 1.0f }),  // wing tips
        glider_point(g, (Vector3){ 1.5f, 0.25f, 1.0f }),
        glider_point(g, (Vector3){ 0.0f, -0.45f, 0.9f }),  // keel
    };
    for (int i = 0; i < 5; ++i) {
        if (points[i].y < surface_height(points[i].x, points[i].z) + 0.05f) return true;
        for (int b = 0; b < BEACON_COUNT; ++b) {
            const Beacon* bc = &island.beacons[b];
            float top = bc->base.y + PILLAR_HEIGHT;
            // pillar (radius 1) and the brazier box on top of it (2.4 wide, 0.6 tall)
            if (horizontal_distance(points[i], bc->base) < 1.1f && points[i].y < top) return true;
            if (fabsf(points[i].x - bc->base.x) < 1.25f && fabsf(points[i].z - bc->base.z) < 1.25f &&
                points[i].y >= top - 0.05f && points[i].y < top + 0.65f) return true;
        }
    }
    return false;
}

static void glider_reset(void) {
    glider = (Glider){0};
    glider.position = (Vector3){ 0.0f, 58.0f, ISLAND_RADIUS + 25.0f };
    glider.yaw = 0.0f;  // facing -Z: toward the island
    glider.speed = TRIM_SPEED;
}

static void glider_update(float dt) {
    bool left = input.pressed[KEY_A] || input.pressed[KEY_LEFT];
    bool right = input.pressed[KEY_D] || input.pressed[KEY_RIGHT];
    bool dive = input.pressed[KEY_W] || input.pressed[KEY_UP];
    bool climb = input.pressed[KEY_S] || input.pressed[KEY_DOWN];

    // Bank; the wings level by themselves when you let go.
    if (left != right) glider.bank += (right ? BANK_RATE : -BANK_RATE) * dt;
    else glider.bank = approach(glider.bank, 0.0f, LEVEL_RATE * dt);
    glider.bank = clamp(glider.bank, -MAX_BANK, MAX_BANK);

    // Pitch; a stalled glider drops its nose until it has speed again.
    if (glider.speed < STALL_SPEED) glider.stalled = true;
    if (glider.stalled && glider.speed > STALL_SPEED + 3.0f) glider.stalled = false;
    if (glider.stalled) {
        glider.pitch = approach(glider.pitch, -0.6f, 1.5f * dt);
    } else if (dive != climb) {
        glider.pitch += (climb ? PITCH_RATE : -PITCH_RATE) * dt;
    } else {
        glider.pitch = approach(glider.pitch, 0.0f, PITCH_RETURN * dt);
    }
    glider.pitch = clamp(glider.pitch, MIN_PITCH, MAX_PITCH);

    // Turning follows the bank.
    glider.yaw = wrap_angle(glider.yaw + TURN_RATE * sinf(glider.bank) * dt);

    // Past the edge of the map the wind turns you back.
    float dist = sqrtf(glider.position.x * glider.position.x + glider.position.z * glider.position.z);
    glider.out_of_bounds = dist > BOUNDS_RADIUS;
    if (glider.out_of_bounds) {
        float home = atan2f(-glider.position.x, glider.position.z);  // yaw that points at the centre
        float err = wrap_angle(home - glider.yaw);
        float push = clamp01((dist - BOUNDS_RADIUS) / 20.0f) * 1.2f * dt;
        glider.yaw = wrap_angle(glider.yaw + clamp(err, -push, push));
    }

    // Speed: gravity along the flight path, drag toward the trim speed.
    glider.speed += (-GRAVITY * sinf(glider.pitch) - DRAG * (glider.speed - TRIM_SPEED)) * dt;
    glider.speed = clamp(glider.speed, 2.0f, 45.0f);

    // Sinking: more when banked, when flying fast, and when mushing along too slow.
    float off_trim = (glider.speed - TRIM_SPEED) / TRIM_SPEED;
    float sink = SINK_RATE * (1.0f + off_trim * off_trim * 1.5f) / fmaxf(cosf(glider.bank), 0.3f);
    if (glider.speed < TRIM_SPEED) sink += (TRIM_SPEED - glider.speed) * 0.5f;

    float lift = thermal_lift_at(glider.position, &glider.in_lift);

    float horizontal = glider.speed * cosf(glider.pitch);
    glider.vertical_speed = glider.speed * sinf(glider.pitch) - sink + lift;
    glider.position.x += sinf(glider.yaw) * horizontal * dt;
    glider.position.z += -cosf(glider.yaw) * horizontal * dt;
    glider.position.y += glider.vertical_speed * dt;
    if (glider.position.y > CEILING) {
        glider.position.y = CEILING;
        glider.vertical_speed = 0.0f;
    }
}

