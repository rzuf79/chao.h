static void init(void) {
    font = ascii_font_create(assets_load_bitmap("font", "assets/fonts/cp437_8x8.png"), true);
    platform_set_window_size(CANVAS_W * WINDOW_SCALE, CANVAS_H * WINDOW_SCALE);

    chao_3d_directional_light.enabled = true;
    chao_3d_directional_light.direction = vector3_get_normalized((Vector3){ -0.5f, 0.8f, -0.3f });  // toward the sun
    chao_3d_directional_light.ambient = 0.45f;

    create_models();
    new_island();
    glider_reset();
    visibility = VIS_START;
}

static void update(float dt) {
    game_tick(dt);
    game_draw(dt);
}

int main(void) {
    chao_run("Beacon Run", CANVAS_W, CANVAS_H, &init, &update);
    free_models();
    ascii_font_free(font);
    return 0;
}
