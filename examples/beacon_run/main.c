static void show_message(const char* text) {
    snprintf(message, sizeof message, "%s", text);
    tweener_remove(&message_scale);
    tweener_remove(&message_alpha);
    message_scale = 0.5f;
    message_alpha = 1.0f;
    tween_float(&message_scale, 2.0f, 0.35f, 0.0f, EASE_BACK_OUT, TWEEN_REPEAT_ONCE);
    tween_float(&message_alpha, 0.0f, 0.6f, 1.6f, EASE_SINE_IN, TWEEN_REPEAT_ONCE);
}

static void start_run(void) {
    for (int b = 0; b < BEACON_COUNT; ++b) island.beacons[b].lit = false;
    glider_reset();
    visibility = VIS_START;
    elapsed = 0.0f;
    beacons_lit = 0;
    crash_timer = 0.0f;
    sparks_clear();
    message_alpha = 0.0f;
    camera.position = vector3_add(glider.position, (Vector3){ 0.0f, 3.5f, 10.0f });
    state = STATE_PLAYING;
    show_message("LIGHT THE BEACONS");
}

// Back to the title: the island shown behind it should look fresh, not like the last run.
static void go_to_title(void) {
    for (int b = 0; b < BEACON_COUNT; ++b) island.beacons[b].lit = false;
    sparks_clear();
    visibility = VIS_START;
    message_alpha = 0.0f;
    state = STATE_TITLE;
}

static void new_island(void) {
    island_generate((uint32_t)rand() % 10000);
}

static void light_beacon(Beacon* bc) {
    bc->lit = true;
    beacons_lit++;
    visibility = fminf(visibility + VIS_BONUS, VIS_START);
    burst(bc->fire, 120, 14.0f, 0xFFE080FF, 0xFF3010FF, 0.35f, -4.0f);
    if (beacons_lit == BEACON_COUNT) {
        state = STATE_WON;
        if (best_time < 0.0f || elapsed < best_time) best_time = elapsed;
        show_message("ISLAND SAVED!");
    } else {
        char text[32];
        snprintf(text, sizeof text, "BEACON %d/%d", beacons_lit, BEACON_COUNT);
        show_message(text);
    }
}

static void play_tick(float dt) {
    elapsed += dt;
    visibility -= VIS_RATE * dt;
    glider_update(dt);

    for (int b = 0; b < BEACON_COUNT; ++b) {
        Beacon* bc = &island.beacons[b];
        if (!bc->lit && vector3_distance(glider.position, bc->fire) < LIGHT_RADIUS) light_beacon(bc);
    }
    if (state != STATE_PLAYING) return;

    if (glider_collides(&glider)) {
        state = STATE_CRASHED;
        burst(glider.position, 70, 9.0f, 0xF4EFE1FF, 0xB0A890FF, 0.35f, -9.0f);
        show_message("CRASHED");
    } else if (visibility <= VIS_MIN) {
        visibility = VIS_MIN;
        state = STATE_LOST;
        show_message("LOST IN THE FOG");
    }
}

// The whole simulation step, separate from drawing so it can run headless.
static void game_tick(float dt) {
    switch (state) {
        case STATE_TITLE:
            title_time += dt;
            if (input.just_pressed[KEY_SPACE] || input.just_pressed[KEY_ENTER]) start_run();
            else if (input.just_pressed[KEY_N]) new_island();
            break;
        case STATE_PLAYING:
            if (input.just_pressed[KEY_ESC]) { state = STATE_PAUSED; break; }
            play_tick(dt);
            break;
        case STATE_PAUSED:
            if (input.just_pressed[KEY_ESC]) state = STATE_PLAYING;
            else if (input.just_pressed[KEY_Q]) go_to_title();
            break;
        case STATE_CRASHED:
        case STATE_LOST:
        case STATE_WON:
            crash_timer += dt;
            if (input.just_pressed[KEY_R]) start_run();
            else if (input.just_pressed[KEY_N]) { new_island(); start_run(); }
            else if (input.just_pressed[KEY_ESC]) go_to_title();
            break;
    }
    if (state != STATE_PAUSED) {
        anim_time += dt;
        if (state != STATE_TITLE) spawn_ambient_sparks(dt);
        sparks_tick(dt);
    }
}

